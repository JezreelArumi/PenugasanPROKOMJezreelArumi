# 4.2 Animals
animals = ['dog', 'cat', 'rabbit']

# Part 1: print the name of each animal.
for animal in animals:
    print(animal)

# Part 2: print a statement about each animal.
print()
for animal in animals:
    print(f"A {animal} would make a great pet.")

# Part 3: say what they have in common, outside the loop.
print("Any of these animals would make a great pet!")