# 4.1 Pizzas
pizzas = ['pepperoni', 'margherita', 'hawaiian']

# Part 1: print the name of each pizza.
for pizza in pizzas:
    print(pizza)

# Part 2: print a sentence about each pizza.
print()
for pizza in pizzas:
    print(f"I like {pizza} pizza.")

# Part 3: a closing line, outside the loop.
print("I really love pizza!")