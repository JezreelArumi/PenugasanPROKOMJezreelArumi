# 5.7 Favorite Fruit
favorite_fruits = ['mangga', 'durian', 'anggur hijau']

# Independent if statements, so every matching fruit gets a message.
if 'mangga' in favorite_fruits:
    print("Kamu suka banget mangga!")
if 'durian' in favorite_fruits:
    print("Kamu suka banget durian!")
if 'anggur hijau' in favorite_fruits:
    print("Kamu suka banget anggur hijau!")
if 'nanas' in favorite_fruits:
    print("Kamu suka banget nanas!")
if 'semangka' in favorite_fruits:
    print("Kamu suka banget semangka!")