# 8.4 Large Shirts (Kaos Besar)
def buat_kaos(ukuran='besar', tulisan='There is no place for us here'):
    """Tampilkan ringkasan kaos. Bawaannya ukuran besar."""
    print(f"\nKaos ukuran {ukuran} dengan tulisan '{tulisan}'.")


# Kaos ukuran besar dengan tulisan bawaan.
buat_kaos()

# Kaos ukuran sedang dengan tulisan bawaan.
buat_kaos('sedang')

# Kaos dengan ukuran apa pun dan tulisan yang berbeda.
buat_kaos('kecil', 'I am getting married, Gia')